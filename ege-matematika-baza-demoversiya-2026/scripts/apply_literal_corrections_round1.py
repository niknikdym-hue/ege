#!/usr/bin/env python3
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
FILES={
    'a': ROOT/'content'/'tasks-01-07.json',
    'c': ROOT/'content'/'tasks-15-21.json',
}

def load(k): return json.loads(FILES[k].read_text(encoding='utf-8'))
def save(k,d): FILES[k].write_text(json.dumps(d,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

def variant(data,task_no,var_no):
    task=next(t for t in data['tasks'] if t['number']==task_no)
    return next(v for v in task['variants'] if v['variant']==var_no)

def replace_exact(obj,key,old,new,label):
    actual=obj[key]
    if actual!=old:
        raise RuntimeError(f'{label}: expected old value not found\nEXPECTED: {old}\nACTUAL: {actual}')
    obj[key]=new

A=load('a')
C=load('c')

replace_exact(
    variant(A,1,2),'prompt_html',
    '<p>Стоимость проездного билета на месяц составляет 655 рублей, а стоимость билета на одну поездку — 25 рублей. Аня купила проездной и сделала за месяц 47 поездок. На сколько рублей больше она бы потратила, если бы покупала билеты на одну поездку?</p>',
    '<p>Стоимость проездного билета на месяц составляет 655 рублей, а стоимость билета на одну поездку 25 рублей. Аня купила проездной и сделала за месяц 47 поездок. На сколько рублей больше она бы потратила, если бы покупала билеты на одну поездку?</p>',
    '1.2 remove invented dash')

replace_exact(
    variant(A,3,1),'prompt_html',
    '<p>На диаграмме показана среднемесячная температура воздуха в Симферополе за каждый месяц 1988 года. По горизонтали указываются месяцы, по вертикали — температура в градусах Цельсия. Определите по диаграмме наибольшую среднемесячную температуру в Симферополе в 1988 году. Ответ дайте в градусах Цельсия.</p>',
    '<p>На диаграмме показана среднемесячная температура воздуха в Симферополе за каждый месяц 1988 года. По горизонтали указаны месяцы, по вертикали — температура (в градусах Цельсия).</p><p>Определите по диаграмме наибольшую среднемесячную температуру в Симферополе в 1988 году. Ответ дайте в градусах Цельсия.</p>',
    '3.1 literal wording and parentheses')

replace_exact(
    variant(A,3,2),'prompt_html',
    '<p>В нескольких эстафетах, которые проводились в школе, команды показали следующие результаты.</p><p>При подведении итогов для каждой команды баллы по всем эстафетам суммируются. Побеждает команда, набравшая наибольшее количество баллов. Какое итоговое место заняла команда «Чемпионы»?</p>',
    '<p>В нескольких эстафетах, которые проводились в школе, команды показали следующие результаты:</p><p>При подведении итогов для каждой команды баллы по всем эстафетам суммируются. Побеждает команда, набравшая наибольшее количество баллов. Какое итоговое место заняла команда «Чемпионы»?</p>',
    '3.2 colon before table')

table=variant(A,3,2)['table']
old_headers=['Команда','I эстафета','II эстафета','III эстафета']
new_headers=['Команда','I эстафета, баллы','II эстафета, баллы','III эстафета, баллы']
if table['headers']!=old_headers:
    raise RuntimeError(f'3.2 table headers changed unexpectedly: {table["headers"]}')
table['headers']=new_headers

# Preserve the actual source glyph used for N·m in the official PDF text layer.
v72=variant(A,7,2)
v72['prompt_html']=v72['prompt_html'].replace('Н·м','Нꞏм')
v72['right']=[x.replace('Н·м','Нꞏм') for x in v72['right']]

replace_exact(
    variant(C,15,3),'prompt_html',
    '<p>Площадь земель фермерского хозяйства, отведённых под посадку сельскохозяйственных культур, составляет 36 гектаров и распределена между зерновыми и овощными культурами в отношении 2 : 7 соответственно. Сколько гектаров занимают овощные культуры?</p>',
    '<p>Площадь земель фермерского хозяйства, отведённых под посадку сельскохозяйственных культур, составляет 36 гектаров и распределена между зерновыми и овощными культурами в отношении 2:7 соответственно. Сколько гектаров занимают овощные культуры?</p>',
    '15.3 ratio spacing')

replace_exact(
    variant(C,17,3),'continuation_html',
    '<p>Если уравнение имеет больше одного корня, в ответе укажите больший из них.</p>',
    '<p>Если уравнение имеет больше одного корня, в ответе запишите больший из них.</p>',
    '17.3 official verb')

save('a',A)
save('c',C)
print('Applied evidence-based literal corrections round 1')
